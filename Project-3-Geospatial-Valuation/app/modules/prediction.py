import streamlit as st
import plotly.graph_objects as go
import pydeck as pdk

from utils.spatial import (
    find_neighbors,
)

from utils.ui import (
    page_header,
    divider,
    render_html
)


def render(
    nodes_df,
    model,
    feature_columns,
    properties,
):

    page_header(
        "Property Price Prediction",
        icon="⌂",
        subtitle=(
            "Inspect model-driven valuation, market context, "
            "and property characteristics."
        ),
    )

    # ---------------------------------------------------------
    # PROPERTY SELECTOR
    # ---------------------------------------------------------

    node_ids = (
        properties["node_id"]
        .sort_values()
        .tolist()
    )

    selected_node = st.selectbox(
        "Select Property",
        node_ids,
    )

    property_row = (
        properties[
            properties["node_id"]
            == selected_node
        ]
        .iloc[0]
        .copy()
    )

    model_input = (
        property_row[
            feature_columns
        ]
        .to_frame()
        .T
    )

    prediction = float(
        model.predict(
            model_input
        )[0]
    )

    actual_price = float(
        property_row[
            "actual_price"
        ]
    )

    absolute_error = abs(
        actual_price
        - prediction
    )

    percentage_error = (
        absolute_error
        / actual_price
    ) * 100

    # ---------------------------------------------------------
    # HERO VALUATION
    # ---------------------------------------------------------

    render_html(
        f"""
        <div class="gv-hero">
            <div class="gv-hero-kicker">
                PROPERTY VALUATION
            </div>
            <div class="gv-hero-title">
                ${prediction:,.0f}
            </div>
            <div class="gv-hero-copy">
                Estimated market value for property
                <strong>#{selected_node}</strong>.
                The estimate is generated by the selected
                production XGBoost model.
            </div>
            <div class="gv-hero-badge">
                XGBOOST · 11.39% TEST MAPE
            </div>
        </div>
        """
    )

    # ---------------------------------------------------------
    # KPI ROW
    # ---------------------------------------------------------

    c1, c2, c3, c4 = st.columns(4)

    with c1:

        st.metric(
            "Estimated Value",
            f"${prediction:,.0f}",
        )

    with c2:

        st.metric(
            "Observed Price",
            f"${actual_price:,.0f}",
        )

    with c3:

        st.metric(
            "Absolute Error",
            f"${absolute_error:,.0f}",
        )

    with c4:

        st.metric(
            "Percentage Error",
            f"{percentage_error:.2f}%",
        )

    divider()

    # ---------------------------------------------------------
    # PROPERTY PROFILE + LOCATION
    # ---------------------------------------------------------

    left, right = st.columns(
        [1, 1],
        gap="large",
    )

    with left:

        with st.container(
            border=True,
        ):

            st.subheader(
                "Property Profile"
            )

            st.caption(
                "Core characteristics used by the valuation model"
            )

            preferred_columns = [
                "bedrooms",
                "bathrooms",
                "sqft_living",
                "sqft_lot",
                "floors",
                "waterfront",
                "view",
                "condition",
                "grade",
                "sqft_above",
                "sqft_basement",
                "House Age",
                "yr_built",
                "yr_renovated",
            ]

            display_columns = [
                col
                for col in preferred_columns
                if col in property_row.index
            ]

            profile = (
                property_row[
                    display_columns
                ]
                .to_frame(
                    name="Value"
                )
            )

            st.dataframe(
                profile,
                use_container_width=True,
                height=520,
                hide_index=False,
            )

    with right:

        with st.container(
            border=True,
        ):

            st.subheader(
                "Location"
            )

            st.caption(
                "Geographic position of the selected property"
            )

            map_data = [
                {
                    "lat": float(
                        property_row["lat"]
                    ),
                    "long": float(
                        property_row["long"]
                    ),
                    "node_id": selected_node,
                }
            ]

            map_layer = pdk.Layer(
                "ScatterplotLayer",
                data=map_data,
                get_position="[long, lat]",
                get_radius=150,
                get_fill_color=[
                    166,
                    73,
                    59,
                    220,
                ],
                pickable=True,
            )

            map_view = pdk.ViewState(
                latitude=float(
                    property_row["lat"]
                ),
                longitude=float(
                    property_row["long"]
                ),
                zoom=11.5,
                pitch=0,
            )

            location_map = pdk.Deck(
                layers=[
                    map_layer
                ],
                initial_view_state=map_view,
                map_style="light",
                tooltip={
                    "html":
                        "<b>Property:</b> {node_id}<br/>"
                        "<b>Latitude:</b> {lat}<br/>"
                        "<b>Longitude:</b> {long}",
                    "style": {
                        "backgroundColor": "#10151F",
                        "color": "#EFEAE0",
                        "fontSize": "12px",
                    },
                },
            )

            st.pydeck_chart(
                location_map,
                use_container_width=True,
                height=520,
            )

            st.markdown(
                f"""
                <div class="gv-location-coordinates">
                    <span>LAT</span>
                    <strong>{property_row['lat']:.5f}</strong>
                    <span>LONG</span>
                    <strong>{property_row['long']:.5f}</strong>
                </div>
                """,
                unsafe_allow_html=True,
            )

    divider()
            
    # ---------------------------------------------------------
    # LOCAL NEIGHBORHOOD CONTEXT
    # ---------------------------------------------------------

    st.subheader(
        "Local Spatial Context"
    )

    neighbors = find_neighbors(
        properties,
        property_row["lat"],
        property_row["long"],
        n_neighbors=10,
    )

    if len(neighbors) > 0:

        local_median = (
            neighbors[
                "actual_price"
            ].median()
        )

        local_mean = (
            neighbors[
                "actual_price"
            ].mean()
        )

        price_position = (
            (
                actual_price
                - local_median
            )
            / local_median
        ) * 100

        n1, n2, n3 = st.columns(3)

        with n1:

            st.metric(
                "Nearby Median",
                f"${local_median:,.0f}",
            )

        with n2:

            st.metric(
                "Nearby Mean",
                f"${local_mean:,.0f}",
            )

        with n3:

            st.metric(
                "Vs Nearby Median",
                f"{price_position:+.1f}%",
            )

        chart_df = (
            neighbors[
                [
                    "node_id",
                    "distance_km",
                    "actual_price",
                ]
            ]
            .sort_values(
                "distance_km"
            )
        )

        fig = go.Figure()

        fig.add_trace(
            go.Scatter(
                x=chart_df["distance_km"],
                y=chart_df["actual_price"],
                mode="lines+markers",
                name="Nearby Properties",
            )
        )

        fig.add_hline(
            y=actual_price,
            line_dash="dash",
            annotation_text="Selected Property",
        )

        fig.update_layout(
            title="Price vs Distance to Selected Property",
            xaxis_title="Distance (km)",
            yaxis_title="Actual Price ($)",
            height=420,
            plot_bgcolor="#FBFAF6",
            paper_bgcolor="#FBFAF6",
        )

        st.plotly_chart(
            fig,
            use_container_width=True,
        )

    st.caption(
        "Neighborhood statistics are calculated from the "
        "nearest spatial properties."
    )